let written = 0, kept = 0;
for (const [dir, set] of [['tools', TOOLS], ['symbols', SYMBOLS]]) {
  mkdirSync(join(ROOT, dir), { recursive: true });
  for (const [name, rows] of Object.entries(set)) {
    const file = join(ROOT, dir, `${name}.png`);
    if (existsSync(file) && !FORCE) {
      kept++;
      continue;
    }
    writeFileSync(file, png(rows));
    written++;
  }
}
console.log(`placeholder icons: ${written} written, ${kept} existing kept`);
