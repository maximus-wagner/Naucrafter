// Writes placeholder pixel-art PNGs for tool icons and map symbols.
// Never overwrites an existing file (your own icons are safe); pass --force to regenerate all.
// Key colours: '#' black = ink, 'o' white = paper, '+' grey #808080 = shade, '.' transparent.
import { deflateSync } from 'node:zlib';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'assets', 'icons');
const FORCE = process.argv.includes('--force');
const COLORS = { '#': [0, 0, 0, 255], o: [255, 255, 255, 255], '+': [128, 128, 128, 255], '.': [0, 0, 0, 0] };

const CRC = new Uint32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}
function png(rows) {
  const h = rows.length, w = Math.max(...rows.map((r) => r.length));
  const raw = Buffer.alloc((w * 4 + 1) * h);
  rows.forEach((row, y) => {
    for (let x = 0; x < w; x++) {
      const c = COLORS[row[x] ?? '.'];
      if (!c) throw new Error(`Unknown pixel '${row[x]}'`);
      raw.set(c, y * (w * 4 + 1) + 1 + x * 4);
    }
  });
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr.set([8, 6, 0, 0, 0], 8);
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
}

